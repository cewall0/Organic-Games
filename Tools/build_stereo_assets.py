"""Install the book_stereo_cut.py molecules as stereo-NAME @2x images and write Plus/StereoCenters.swift, the
stereocentre positions picked in stereo_picks.json (atom indices from atoms.json, or [x, y] fractions for an atom
drawn as text such as the CH in 7.2's phenylalanine).

usage: build_stereo_assets.py CUTDIR"""
import json, os, shutil, sys
cut = sys.argv[1]; here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(here)
atoms = json.load(open(f"{cut}/atoms.json")); picks = json.load(open(f"{here}/stereo_picks.json"))
# s… molecules (chirality games) → Stereo/stereo-…; i… isomer pairs (Isomer Match) → Isomers/isomer-…
for prefix, folder, asset in [("s", "Stereo", "stereo-"), ("i", "Isomers", "isomer-")]:
    cat = f"{root}/Organic Games/Assets.xcassets/{folder}"
    os.makedirs(cat, exist_ok=True)
    json.dump({"info": {"author": "xcode", "version": 1}, "properties": {"provides-namespace": False}},
              open(f"{cat}/Contents.json", "w"), indent=2)
    for f in sorted(os.listdir(cut)):
        if not f.endswith(".png") or "-" in f or not f.startswith(prefix): continue
        name = asset + f[1:-4]; d = f"{cat}/{name}.imageset"; os.makedirs(d, exist_ok=True)
        shutil.copy(f"{cut}/{f}", f"{d}/{name}.png")
        json.dump({"images": [{"filename": f"{name}.png", "idiom": "universal", "scale": "2x"}],
                   "info": {"author": "xcode", "version": 1}}, open(f"{d}/Contents.json", "w"), indent=2)
from PIL import Image


def snap_atoms(name):
    """Atom positions to snap taps to: points within 4 pt (16 px at 4×) merge, so double bonds and hash marks count
    once. Picked [x, y] centres (atoms drawn as text) are added."""
    w, h = Image.open(f"{cut}/{name}.png").size
    pts = [(x * w, y * h) for x, y in atoms[name]] + [(p[0] * w, p[1] * h) for p in picks.get(name, []) if isinstance(p, list)]
    groups = []
    for x, y in pts:
        for g in groups:
            gx, gy = g[0] / g[2], g[1] / g[2]
            if (gx - x) ** 2 + (gy - y) ** 2 < 16 ** 2: g[0] += x; g[1] += y; g[2] += 1; break
        else: groups.append([x, y, 1])
    return [(g[0] / g[2] / w, g[1] / g[2] / h) for g in groups], w, h


def pt(p): return f"CGPoint(x: {p[0]:.4f}, y: {p[1]:.4f})"


atom_lines, center_lines = [], []
for n in picks:
    snap, w, h = snap_atoms(n)
    centers = []
    for p in picks[n]:
        x, y = atoms[n][p] if isinstance(p, int) else p
        i = min(range(len(snap)), key=lambda k: (snap[k][0] - x) ** 2 * w * w + (snap[k][1] - y) ** 2 * h * h)
        assert ((snap[i][0] - x) * w) ** 2 + ((snap[i][1] - y) * h) ** 2 < 16 ** 2, (n, p)
        centers.append(i)
    atom_lines.append(f'        "stereo-{n[1:]}": [' + ", ".join(pt(p) for p in snap) + "],")
    center_lines.append(f'        "stereo-{n[1:]}": [' + ", ".join(map(str, sorted(centers))) + "],")
open(f"{root}/Organic Games/Plus/StereoCenters.swift", "w").write(
    "//\n//  StereoCenters.swift\n//  Organic Games\n//\n//  Generated by Tools/build_stereo_assets.py from Tools/stereo_picks.json; edit"
    " those, not this file.\n//  atoms: every atom in a drawing (bond ends, wedge tips, Fischer crossings) as fractions of the image\n"
    "//  width and height, for taps to snap to. centers: which of those atoms are stereocenters.\n//\n\n"
    "import CoreGraphics\n\nenum StereoCenters {\n    static let atoms: [String: [CGPoint]] = [\n" + "\n".join(atom_lines)
    + "\n    ]\n\n    static let centers: [String: Set<Int>] = [\n" + "\n".join(center_lines) + "\n    ]\n}\n")
print("ok")
